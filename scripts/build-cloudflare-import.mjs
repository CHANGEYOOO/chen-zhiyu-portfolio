import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const indexPath = resolve(root, "index.html");
const livestreamPath = resolve(root, "assets/data/livestream-projects.json");
const dimensionsPath = resolve(root, "assets/data/livestream-image-dimensions.json");
const seedDirectory = resolve(root, "cloudflare-portfolio-api/seed");
const manifestPath = resolve(seedDirectory, "works.json");
const sqlPath = resolve(seedDirectory, "import.sql");
const mediaHost = "https://media.kjoe.top";

function text(value) {
  return value
    .replace(/<[^>]+>/g, "")
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .trim();
}

function required(match, description) {
  if (!match?.[1]) throw new Error(`Cannot extract ${description}`);
  return text(match[1]);
}

function keyFromMediaUrl(value, description) {
  let url;
  try {
    url = new URL(value);
  } catch {
    throw new Error(`Invalid ${description} URL: ${value}`);
  }
  if (url.origin !== mediaHost) throw new Error(`Unexpected ${description} host: ${url.origin}`);
  return url.pathname.replace(/^\/+/, "");
}

function mediaRelease(key) {
  const match = key.match(/^(media-v[^/]+)\//);
  if (!match) throw new Error(`Cannot extract R2 release from key: ${key}`);
  return match[1];
}

function extractTvc(indexHtml) {
  const videoBase = required(indexHtml.match(/data-video-base="([^"]+)"/), "TVC video base");
  const cards = [...indexHtml.matchAll(/<article class="work-card" data-work="([^"]+)">([\s\S]*?)<\/article>/g)];
  return cards.map(([_, id, card], sortOrder) => {
    const mobileUrl = required(card.match(/<source[^>]+srcset="([^"]+)"/), `mobile poster for ${id}`);
    const desktopUrl = required(card.match(/<img[^>]+src="([^"]+)"/), `desktop poster for ${id}`);
    const meta = card.match(/<p class="work-meta-line">([\s\S]*?)<\/p>/)?.[1];
    if (!meta) throw new Error(`Cannot extract metadata for ${id}`);
    const spans = [...meta.matchAll(/<span>([\s\S]*?)<\/span>/g)].map((match) => text(match[1]));
    if (spans.length !== 2 || !spans.every(Boolean)) throw new Error(`Cannot extract TVC text for ${id}`);
    const posterKey = keyFromMediaUrl(desktopUrl, `desktop poster for ${id}`);
    const release = mediaRelease(posterKey);
    const videoUrl = new URL(`${id}.mp4`, videoBase).href;
    return {
      id,
      section: "tvc",
      brand_name: spans[0],
      work_title: required(card.match(/<h3>([\s\S]*?)<\/h3>/), `title for ${id}`),
      work_type: spans[1],
      poster_key: posterKey,
      poster_mobile_key: keyFromMediaUrl(mobileUrl, `mobile poster for ${id}`),
      video_key: keyFromMediaUrl(videoUrl, `video for ${id}`),
      sort_order: sortOrder,
      images: [],
      release,
    };
  });
}

function extractLivestream(projects, dimensions, release) {
  return projects.map((project, sortOrder) => {
    if (!project?.id || !project.title || !project.category || !project.directory || !Array.isArray(project.images)) {
      throw new Error(`Invalid Livestream source project at index ${sortOrder}`);
    }
    const images = project.images.map((filename, imageOrder) => {
      const dimension = dimensions[`${project.directory}/${filename}`];
      if (!Array.isArray(dimension) || dimension.length !== 2 || !dimension.every(Number.isInteger)) {
        throw new Error(`Missing image dimensions for ${project.directory}/${filename}`);
      }
      return {
        id: `${project.id}-image-${String(imageOrder + 1).padStart(3, "0")}`,
        image_key: `${release}/assets/images/livestream/${project.directory}/${filename}`,
        sort_order: imageOrder,
        width: dimension[0],
        height: dimension[1],
      };
    });
    return {
      id: project.id,
      section: "livestream",
      brand_name: null,
      work_title: project.title,
      work_type: project.category,
      poster_key: null,
      poster_mobile_key: null,
      video_key: null,
      cover_key: images[0]?.image_key || null,
      sort_order: sortOrder,
      images,
    };
  });
}

function sqlText(value) {
  if (value === null) return "NULL";
  if (typeof value === "number") return String(value);
  return `'${String(value).replace(/'/g, "''")}'`;
}

function buildSql(works) {
  const columns = ["id", "section", "brand_name", "work_title", "work_type", "poster_key", "poster_mobile_key", "video_key", "sort_order", "status", "version"];
  const updates = columns.slice(1).map((column) => `${column} = excluded.${column}`).join(", ");
  const lines = [
    "-- Generated by scripts/build-cloudflare-import.mjs. Do not edit by hand.",
    "-- Existing R2 objects are referenced only; this file performs no upload.",
    "BEGIN;",
  ];

  for (const work of works) {
    const values = [
      work.id,
      work.section,
      work.brand_name,
      work.work_title,
      work.work_type,
      work.poster_key,
      work.poster_mobile_key,
      work.video_key,
      work.sort_order,
      "published",
      1,
    ].map(sqlText).join(", ");
    lines.push(`INSERT INTO works (${columns.join(", ")}) VALUES (${values}) ON CONFLICT(id) DO UPDATE SET ${updates};`);
  }

  for (const work of works.filter((item) => item.section === "livestream")) {
    for (const image of work.images) {
      const values = [image.id, work.id, image.image_key, image.sort_order, image.width, image.height].map(sqlText).join(", ");
      lines.push(`INSERT INTO work_images (id, work_id, image_key, sort_order, width, height) VALUES (${values}) ON CONFLICT(id) DO UPDATE SET work_id = excluded.work_id, image_key = excluded.image_key, sort_order = excluded.sort_order, width = excluded.width, height = excluded.height;`);
    }
  }

  lines.push("COMMIT;", "");
  return lines.join("\n");
}

const indexHtml = readFileSync(indexPath, "utf8");
const projects = JSON.parse(readFileSync(livestreamPath, "utf8"));
const dimensions = JSON.parse(readFileSync(dimensionsPath, "utf8"));
const tvc = extractTvc(indexHtml);
if (tvc.length !== 30) throw new Error(`Expected 30 TVC cards, found ${tvc.length}`);
const release = mediaRelease(tvc[0]?.poster_key || "");
if (tvc.some((work) => work.release !== release)) throw new Error("TVC media paths do not share one R2 release");
const works = [...tvc.map(({ release: _, ...work }) => work), ...extractLivestream(projects, dimensions, release)];
const manifest = { manifest_version: 1, media_host: mediaHost, works };

mkdirSync(seedDirectory, { recursive: true });
writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
writeFileSync(sqlPath, buildSql(works));
const imageCount = projects.reduce((total, project) => total + project.images.length, 0);
console.log(`Built Cloudflare import: TVC=${tvc.length} Livestream=${projects.length} Images=${imageCount}`);
